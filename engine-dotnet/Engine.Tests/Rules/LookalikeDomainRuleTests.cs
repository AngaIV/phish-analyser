using MimeKit;
using PhishAnalyser.Engine.Models;
using PhishAnalyser.Engine.Rules;
using Xunit;

namespace PhishAnalyser.Engine.Tests.Rules;

public class LookalikeDomainRuleTests
{
    private static LookalikeDomainRule Rule => new();

    private static MimeMessage Message(string? from)
    {
        var message = new MimeMessage();
        if (from is not null)
            message.Headers.Add("From", from);
        return message;
    }

    private static Finding Only(IReadOnlyList<Finding> results) => Assert.Single(results);

    [Fact]
    public void BrandWithLureWord_IsFlaggedHigh()
    {
        var finding = Only(Rule.Evaluate(Message("<service@paypal-secure.com>")));

        Assert.Equal(RuleStatus.Flagged, finding.Status);
        Assert.Equal(Severity.High, finding.Severity);
        Assert.Equal(3, finding.Weight);
    }

    [Fact]
    public void BrandWithLureWordInSeparateLabels_IsFlaggedHigh()
    {
        var finding = Only(Rule.Evaluate(Message("<x@paypal.secure-login.com>")));

        Assert.Equal(RuleStatus.Flagged, finding.Status);
        Assert.Equal(Severity.High, finding.Severity);
    }

    [Fact]
    public void BrandOnItsOwnSubdomain_IsPass()
    {
        // support.apple.com is Apple's real support host, not a lookalike.
        var finding = Only(Rule.Evaluate(Message("<x@support.apple.com>")));

        Assert.Equal(RuleStatus.Pass, finding.Status);
    }

    [Fact]
    public void BrandAliasDomain_IsPass()
    {
        var finding = Only(Rule.Evaluate(Message("<x@support.microsoft.com>")));

        Assert.Equal(RuleStatus.Pass, finding.Status);
    }

    [Fact]
    public void CheapTld_IsFlaggedMedium()
    {
        var finding = Only(Rule.Evaluate(Message("<x@tontransport.ga>")));

        Assert.Equal(RuleStatus.Flagged, finding.Status);
        Assert.Equal(Severity.Medium, finding.Severity);
        Assert.Equal(2, finding.Weight);
    }

    [Fact]
    public void IpDerivedLabel_IsFlaggedMedium()
    {
        var finding = Only(Rule.Evaluate(Message("<x@v133-18-229-1.vir.kagoya.net>")));

        Assert.Equal(RuleStatus.Flagged, finding.Status);
        Assert.Equal(Severity.Medium, finding.Severity);
        Assert.Equal(2, finding.Weight);
    }

    [Fact]
    public void LongDigitRun_IsFlaggedMedium()
    {
        var finding = Only(Rule.Evaluate(Message("<x@em5269.xfund02.ml>")));

        Assert.Equal(RuleStatus.Flagged, finding.Status);
        Assert.Equal(Severity.Medium, finding.Severity);
        Assert.Equal(2, finding.Weight);
    }

    [Fact]
    public void ShortDigitRun_IsNotTreatedAsAutoGenerated()
    {
        // "mx01" is an ordinary mail-host label, not evidence.
        var finding = Only(Rule.Evaluate(Message("<x@mx01.example.com>")));

        Assert.Equal(RuleStatus.Pass, finding.Status);
    }

    [Fact]
    public void ShortBrandWithLureWord_IsNotMatched()
    {
        // Documented limitation: "ups" is excluded because it matches arbitrary words.
        var finding = Only(Rule.Evaluate(Message("<x@ups-secure.com>")));

        Assert.Equal(RuleStatus.Pass, finding.Status);
    }

    [Fact]
    public void OrdinaryDomain_IsPass()
    {
        var finding = Only(Rule.Evaluate(Message("<john@example.com>")));

        Assert.Equal(RuleStatus.Pass, finding.Status);
    }

    [Fact]
    public void MissingFrom_IsUnknown()
    {
        var finding = Only(Rule.Evaluate(Message(null)));

        Assert.Equal(RuleStatus.Unknown, finding.Status);
    }
}